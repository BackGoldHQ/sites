// `@backgold/content/codegen` — `generateTypes`, the pure generator the
// `backgold-content types` CLI (src/cli.ts) wraps. It turns `GET /types` into
// a module that augments `BackgoldTypeMap`, so `entry(type, slug)` returns
// typed `fields`.
import type { GenerateTypes } from './contract.js'
import { renderTypes } from './codegen-render.js'

export type { GenerateTypes, GenerateTypesOptions } from './contract.js'

/**
 * One `BackgoldFields` member per type, in the api's order, each field in the
 * api's order with its label as a trailing comment; the augmentation gives
 * `BackgoldTypeMap` one own member per type. `generatedAt` defaults to
 * today's date (no time): the same types and the same `generatedAt` (the
 * CLI's `--generated-at`) give the same bytes. A field typed without `| null`
 * is one the type requires, which holds for published entries; a preview
 * read of a draft may answer null for any field.
 */
export const generateTypes: GenerateTypes = (types, opts = {}) => {
  const moduleName = opts.moduleName ?? '@backgold/content'
  const generatedAt = opts.generatedAt ?? new Date().toISOString().slice(0, 10)
  return renderTypes({
    types,
    header: [
      `Generated by @backgold/content from GET /types on ${generatedAt}. Do not edit by hand.`,
      'Re-run: npx backgold-content types --out <this file>',
      'Required fields hold for published entries; a preview read may answer null for any field.',
    ],
    moduleName,
    style: 'own',
  })
}
