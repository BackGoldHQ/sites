test('generateTypes: deterministic, and the default date is today with no time', () => {
  assert.equal(generateTypes(FIXTURE), generateTypes(FIXTURE))
  const today = new Date().toISOString().slice(0, 10)
  assert.match(generateTypes([]), new RegExp(`from GET /types on ${today}\\. Do not edit by hand\\.\\n`))
})

test('generateTypes: moduleName is quoted into the augmentation', () => {
  const text = generateTypes([], { moduleName: "my-'content", generatedAt: 'x' })
  assert.match(text, /^declare module 'my-\\'content' \{$/m)
  assert.match(text, /^export interface BackgoldFields \{\}$/m)
  assert.match(text, /^ {2}interface BackgoldTypeMap \{\}$/m)
})

